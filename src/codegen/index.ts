function toJniType(type: FFIType): string {
  if (typeof type === 'string') {
    switch (type) {
      case 'void': return 'void';
      case 'bool': return 'jboolean';
      case 'int8': return 'jbyte';
      case 'uint8': return 'jbyte';
      case 'int16': return 'jshort';
      case 'uint16': return 'jshort';
      case 'int32': return 'jint';
      case 'uint32': return 'jint';
      case 'int64': return 'jlong';
      case 'uint64': return 'jlong';
      case 'float': return 'jfloat';
      case 'double': return 'jdouble';
      case 'string': return 'jstring';
      case 'wstring': return 'jstring';
      case 'pointer': return 'jlong';
      case 'buffer': return 'jbyteArray';
    }
  }
  return 'jobject';
}
