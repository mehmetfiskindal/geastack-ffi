/**
 * @geastack/ffi - C/C++, Objective-C++, and JNI Code Generator
 * Generates native platform headers and glue code directly from TypeScript FFI definitions.
 */

import { FFIType, PrimitiveType, StructDefinition, FunctionDescriptor } from '../types.js';

export interface CodegenOptions {
  readonly moduleName: string;
  readonly structs?: Record<string, StructDefinition<any>>;
  readonly functions?: Record<string, FunctionDescriptor<any, any>>;
  readonly headerGuard?: string;
}

export function toCType(type: FFIType): string {
  if (typeof type === 'string') {
    switch (type) {
      case 'void': return 'void';
      case 'bool': return 'bool';
      case 'int8': return 'int8_t';
      case 'uint8': return 'uint8_t';
      case 'int16': return 'int16_t';
      case 'uint16': return 'uint16_t';
      case 'int32': return 'int32_t';
      case 'uint32': return 'uint32_t';
      case 'int64': return 'int64_t';
      case 'uint64': return 'uint64_t';
      case 'float': return 'float';
      case 'double': return 'double';
      case 'string': return 'const char*';
      case 'wstring': return 'const wchar_t*';
      case 'pointer': return 'void*';
      case 'buffer': return 'uint8_t*';
    }
  }
  if ('__isStruct' in type) {
    return `${type.name}*`;
  }
  return 'void*';
}

/**
 * Generate a C/C++ header file (.h).
 */
export function generateCHeader(options: CodegenOptions): string {
  const guard = options.headerGuard || `GEA_FFI_${options.moduleName.toUpperCase()}_H`;
  const lines: string[] = [
    `// Auto-generated by @geastack/ffi. DO NOT EDIT MANUALLY.`,
    `#ifndef ${guard}`,
    `#define ${guard}`,
    ``,
    `#include <stdint.h>`,
    `#include <stdbool.h>`,
    `#include <stddef.h>`,
    `#include <wchar.h>`,
    ``,
    `#if defined(_WIN32)`,
    `  #define GEA_FFI_EXPORT __declspec(dllexport)`,
    `#elif defined(__GNUC__) || defined(__clang__)`,
    `  #define GEA_FFI_EXPORT __attribute__((visibility("default")))`,
    `#else`,
    `  #define GEA_FFI_EXPORT`,
    `#endif`,
    ``,
    `#ifdef __cplusplus`,
    `extern "C" {`,
    `#endif`,
    ``,
  ];

  // Generate struct declarations
  if (options.structs) {
    for (const struct of Object.values(options.structs)) {
      lines.push(`typedef struct ${struct.name} {`);
      for (const [fieldName, field] of Object.entries(struct.fields)) {
        lines.push(`    ${toCType(field.type)} ${fieldName};`);
      }
      lines.push(`} ${struct.name};`, ``);
    }
  }

  // Generate function prototypes
  if (options.functions) {
    for (const [name, fn] of Object.entries(options.functions)) {
      const symbolName = fn.symbol || name;
      const retType = toCType(fn.returns);
      const argsList = fn.args.length === 0
        ? 'void'
        : fn.args.map((arg: FFIType, i: number) => `${toCType(arg)} arg${i}`).join(', ');
      lines.push(`${retType} ${symbolName}(${argsList});`);
    }
    lines.push(``);
  }

  lines.push(
    `#ifdef __cplusplus`,
    `}`,
    `#endif`,
    ``,
    `#endif // ${guard}`,
    ``
  );

  return lines.join('\n');
}

/**
 * Generate an Objective-C++ bridge file (.mm) for iOS & macOS.
 */
export function generateAppleObjCpp(options: CodegenOptions, imports: string[] = []): string {
  const lines: string[] = [
    `// Auto-generated Objective-C++ bridge by @geastack/ffi`,
    `#import <Foundation/Foundation.h>`,
    ...imports.map(imp => `#import ${imp}`),
    `#include "${options.moduleName}.h"`,
    ``,
    `extern "C" {`,
    ``,
  ];

  if (options.functions) {
    for (const [name, fn] of Object.entries(options.functions)) {
      const symbolName = fn.symbol || name;
      const retType = toCType(fn.returns);
      const argsList = fn.args.length === 0
        ? 'void'
        : fn.args.map((arg: FFIType, i: number) => `${toCType(arg)} arg${i}`).join(', ');

      lines.push(`${retType} ${symbolName}(${argsList}) {`);
      lines.push(`    // Native Apple SDK implementation body`);
      if (retType === 'void') {
        lines.push(`    // [NativeTarget ${name}];`);
      } else if (retType === 'const char*') {
        lines.push(`    return "";`);
      } else if (retType === 'const wchar_t*') {
        lines.push(`    return L"";`);
      } else if (retType.includes('*')) {
        lines.push(`    return NULL;`);
      } else if (retType === 'bool') {
        lines.push(`    return true;`);
      } else {
        lines.push(`    return 0;`);
      }
      lines.push(`}`, ``);
    }
  }

  lines.push(`}`, ``);
  return lines.join('\n');
}

/**
 * Generate a C++ JNI bridge file (.cpp) for Android.
 */
export function generateAndroidJni(
  options: CodegenOptions,
  javaPackage: string,
  javaClass: string
): string {
  const pkgPrefix = javaPackage.replace(/\./g, '_');
  const classPrefix = `Java_${pkgPrefix}_${javaClass}`;

  const lines: string[] = [
    `// Auto-generated Android JNI bridge by @geastack/ffi`,
    `#include <jni.h>`,
    `#include <string>`,
    `#include "${options.moduleName}.h"`,
    ``,
    `extern "C" {`,
    ``,
  ];

  if (options.functions) {
    for (const [name, fn] of Object.entries(options.functions)) {
      const jniName = `${classPrefix}_native${name.charAt(0).toUpperCase() + name.slice(1)}`;
      const jniRetType = toJniType(fn.returns);

      const jniArgs = [
        'JNIEnv* env',
        'jobject thiz',
        ...fn.args.map((arg: FFIType, idx: number) => `${toJniType(arg)} arg${idx}`),
      ].join(', ');

      lines.push(`JNIEXPORT ${jniRetType} JNICALL`);
      lines.push(`${jniName}(${jniArgs}) {`);
      lines.push(`    // Route call to C / C++ native layer`);
      if (jniRetType === 'void') {
        lines.push(`    // ${fn.symbol || name}(...);`);
      } else if (jniRetType === 'jstring') {
        lines.push(`    return env->NewStringUTF("");`);
      } else if (jniRetType === 'jboolean') {
        lines.push(`    return JNI_TRUE;`);
      } else {
        lines.push(`    return 0;`);
      }
      lines.push(`}`, ``);
    }
  }

  lines.push(`}`, ``);
  return lines.join('\n');
}

