/**
 * Keep `package.json` as the single source of truth for the package version.
 *
 * Updates:
 * - `src/version.ts` (the runtime constant exported by the package)
 * - `gea-plugin.json` (the GeaStack plugin manifest)
 *
 * Usage:
 *   node scripts/sync-version.mjs          # rewrite both files
 *   node scripts/sync-version.mjs --check  # fail when either file is stale
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
const version = String(pkg.version);

const versionSource = `// SPDX-License-Identifier: Apache-2.0
/**
 * Generated by \`npm run sync-version\` from package.json.
 * Do not edit by hand: change package.json and run \`npm run sync-version\`.
 */
export const VERSION = '${version}';
`;

const pluginPath = path.join(root, 'gea-plugin.json');
const pluginSource = readFileSync(pluginPath, 'utf8').replace(
  /("version"\s*:\s*")[^"]*(")/,
  `$1${version}$2`
);

const stale = [];

function apply(file, next) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (current === next) return;
  if (checkOnly) {
    stale.push(path.relative(root, file));
    return;
  }
  writeFileSync(file, next);
  console.log(`updated ${path.relative(root, file)}`);
}

apply(path.join(root, 'src/version.ts'), versionSource);
apply(pluginPath, pluginSource);

if (checkOnly && stale.length > 0) {
  console.error(`Version ${version} in package.json is not reflected in:`);
  for (const file of stale) console.error(`  - ${file}`);
  console.error('Run `npm run sync-version` and commit the result.');
  process.exit(1);
}
